    /// 검색어가 들어간 말의 이모지와, 분류 이름이 맞으면 그 분류 전체
    static func search(_ query: String) -> [String] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return [] }
        var out: [String] = []
        var seen = Set<String>()
        func add(_ list: [String]) {
            for e in list where !seen.contains(e) {
                seen.insert(e)
                out.append(e)
            }
        }
        for (words, emoji) in keywords where words.split(separator: " ").contains(where: { $0.hasPrefix(q) }) {
            add(list(emoji))
        }
        for c in categories where c.name.contains(q) { add(c.items) }
        return out
    }
